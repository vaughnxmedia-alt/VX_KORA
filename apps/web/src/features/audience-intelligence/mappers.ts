import type { AudienceProfile } from "./types";

function parseArray<T>(value: unknown, fallback: T[]): T[] {
  if (Array.isArray(value)) return value as T[];
  if (typeof value === "string") {
    try {
      const parsed = JSON.parse(value);
      return Array.isArray(parsed) ? (parsed as T[]) : fallback;
    } catch {
      return fallback;
    }
  }
  return fallback;
}

export function mapAudienceAnalysisToProfile(row: any, clientName: string): AudienceProfile {
  const segments = parseArray<any>(row.audience_segments, []).map((segment: any, index: number) => ({
    id: `${row.id}-segment-${index}`,
    name: segment.name || `Segment ${index + 1}`,
    description: segment.description || "",
    painPoint: segment.pain_point || "",
    whyTheyFollow: segment.why_they_follow || "",
    whyTheyHesitate: segment.why_they_hesitate || "",
    buyingMotivation: segment.buying_motivation || "",
    bestContentAngle: segment.best_content_angle || "",
    bestCta: segment.best_cta || "",
  }));

  const personas = parseArray<any>(row.personality_types, []).map((persona: any, index: number) => ({
    id: `${row.id}-persona-${index}`,
    name: persona.name || `Persona ${index + 1}`,
    roleTitle: persona.role || "",
    stageOfBusiness: persona.stage || "",
    goals: parseArray<string>(persona.goals, []),
    fears: parseArray<string>(persona.fears, []),
    objections: parseArray<string>(persona.objections, []),
    platformsUsed: parseArray<string>(persona.platforms, []),
    resonantMessaging: parseArray<string>(persona.messaging, []),
    offerFit: persona.offer_fit || "",
  }));

  const platforms = parseArray<any>(row.platform_breakdown, []).map((platform: any) => ({
    platform: platform.platform || "Instagram",
    relevanceScore: Number(platform.relevance_score || 0),
    bestContentType: platform.content_style || "",
    toneStyle: platform.tone_style || "",
    conversionRole: platform.conversion_role || "",
  }));

  const motivations = parseArray<string>(row.audience_motivations, []);
  const contentAttraction = parseArray<any>(row.content_types_that_attract, []);

  return {
    id: row.id,
    clientId: row.client_id,
    clientName,
    audienceName: row.title || `${clientName} Core Audience`,
    linkedAsset: row.linked_asset || "Primary Offer",
    linkedAssetType: row.linked_asset_type || "offer",
    audienceCategory: row.audience_category || "core",
    description: row.overview || "Audience intelligence profile generated by KORA.",
    status: row.status || "complete",
    audienceType: row.audience_type || "ai_generated",
    segments,
    personas,
    platformIntelligence: platforms,
    psychology: {
      motivations,
      fears: parseArray<string>(row.audience_fears, []),
      trustDrivers: parseArray<string>(row.trust_drivers, []),
      emotionalTriggers: parseArray<string>(row.emotional_triggers, []),
      buyingBarriers: parseArray<string>(row.buying_barriers, []),
    },
    coreProfile: {
      demographics: row.demographics || "",
      psychographics: row.psychographics || "",
      behaviors: row.behaviors || "",
      motivations: motivations.join(", "),
      painPoints: row.pain_points || "",
      objections: row.objections || "",
      buyingTriggers: row.buying_triggers || "",
      desiredTransformation: row.desired_transformation || "",
    },
    contentInsights: {
      hooks: contentAttraction.find((c: any) => c.type === "Hooks")?.examples || [],
      storyAngles: contentAttraction.find((c: any) => c.type === "Story Angles")?.examples || [],
      educationalThemes: contentAttraction.find((c: any) => c.type === "Educational Themes")?.examples || [],
      trustBuilding: contentAttraction.find((c: any) => c.type === "Trust Building")?.examples || [],
      conversionContent: contentAttraction.find((c: any) => c.type === "Conversion")?.examples || [],
      contentToAvoid: contentAttraction.find((c: any) => c.type === "Avoid")?.examples || [],
    },
    messagingGuidance: {
      resonantLanguage: parseArray<string>(row.resonant_language, []),
      trustedWords: parseArray<string>(row.trusted_words, []),
      turnOffLanguage: parseArray<string>(row.turnoff_language, []),
      toneDirection: row.tone_direction || "",
      positioningNotes: row.core_positioning || "",
      ctaSuggestions: parseArray<string>(row.cta_suggestions, []),
    },
    analysisRun: {
      generatedBy: "Audience Intelligence Agent",
      triggeredBy: row.triggered_by || "intake",
      sourceInputsUsed: parseArray<string>(row.source_inputs, ["KORA intake"]),
      analysisDate: row.generated_at || row.created_at,
      lastRunAt: row.generated_at || row.created_at,
      confidenceLevel: Number(row.confidence_score || 0),
      humanEdited: Boolean(row.human_edited),
      needsReview: row.status === "needs_review",
      runVersion: Number(row.report_version || 1),
    },
    confidenceScore: Number(row.confidence_score || 0),
    completenessScore: Number(row.completeness_score || 0),
    createdBy: row.created_by || "KORA Agent",
    createdAt: row.created_at,
    updatedAt: row.generated_at || row.updated_at || row.created_at,
  };
}
