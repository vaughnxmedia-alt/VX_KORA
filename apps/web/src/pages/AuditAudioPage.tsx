import { useEffect } from "react";
import { Link, useParams } from "react-router-dom";
import { useQuery } from "@tanstack/react-query";
import { Headphones, Loader2 } from "lucide-react";
import { Button } from "@/components/ui/button";
import { supabase } from "@/integrations/supabase/client";

type AuditAudioPayload = {
  businessName: string;
  contactName?: string | null;
  audioUrl: string;
  audioMode?: string | null;
  generatedAt?: string | null;
  estimatedMinutes?: number | null;
  wordCount?: number | null;
};

function modeLabel(value: string | null | undefined): string {
  if (value === "podcast_deep_dive") return "Podcast Deep Dive";
  if (value === "executive_recap") return "Executive Recap";
  return "Private Strategy Brief";
}

export default function AuditAudioPage() {
  const { businessSlug } = useParams<{ businessSlug: string }>();

  useEffect(() => {
    document.title = "Private Audio Strategy Brief | JahKnowsPR";
    let robots = document.querySelector('meta[name="robots"]') as HTMLMetaElement | null;
    if (!robots) {
      robots = document.createElement("meta");
      robots.name = "robots";
      document.head.appendChild(robots);
    }
    robots.content = "noindex,nofollow";
  }, []);

  const { data, isLoading, error } = useQuery({
    queryKey: ["audit-audio-page", businessSlug],
    enabled: Boolean(businessSlug),
    queryFn: async () => {
      const { data: response, error: functionError } = await supabase.functions.invoke("audit-audio-page", {
        body: { slug: businessSlug },
      });
      if (functionError) throw functionError;
      return response as AuditAudioPayload;
    },
  });

  return (
    <main className="min-h-screen bg-[#F7F3EA] px-4 py-12 text-[#0A1A35] sm:px-6">
      <section className="mx-auto flex min-h-[calc(100vh-6rem)] max-w-3xl flex-col justify-center">
        <div className="rounded-[2rem] border border-[#D8C28B]/70 bg-white p-6 shadow-xl shadow-[#0A1A35]/10 md:p-10">
          <div className="mb-8 flex items-center gap-3">
            <div className="flex h-12 w-12 items-center justify-center rounded-full bg-[#0A1A35] text-white">
              <Headphones className="h-6 w-6" />
            </div>
            <div>
              <p className="text-xs font-bold uppercase tracking-[0.24em] text-[#A77B22]">JahKnowsPR Firm</p>
              <h1 className="font-serif text-3xl font-bold md:text-5xl">Private Audio Strategy Brief</h1>
            </div>
          </div>

          {isLoading ? (
            <div className="flex items-center gap-3 rounded-2xl bg-[#F7F3EA] p-5 text-sm">
              <Loader2 className="h-4 w-4 animate-spin" />
              Loading your private audio brief...
            </div>
          ) : error || !data?.audioUrl ? (
            <div className="rounded-2xl border border-[#D8C28B]/70 bg-[#F7F3EA] p-5">
              <h2 className="font-semibold">Audio brief not available yet.</h2>
              <p className="mt-2 text-sm text-[#0A1A35]/70">
                This private link may still be processing, or the audit audio may need to be regenerated by the JahKnowsPR team.
              </p>
              <Button className="mt-5" asChild>
                <Link to="/free-audit">Start a Free Audit</Link>
              </Button>
            </div>
          ) : (
            <div className="space-y-6">
              <div>
                <p className="text-sm font-semibold uppercase tracking-[0.2em] text-[#A77B22]">
                  {modeLabel(data.audioMode)}
                </p>
                <h2 className="mt-2 text-2xl font-bold">{data.businessName}</h2>
                <p className="mt-2 text-[#0A1A35]/70">
                  A private JahKnowsPR audio note created from your audit diagnosis.
                </p>
              </div>

              <audio controls src={data.audioUrl} className="w-full">
                <a href={data.audioUrl}>Play Audio Strategy Brief</a>
              </audio>

              <div className="rounded-2xl bg-[#F7F3EA] p-5 text-sm text-[#0A1A35]/75">
                <p>
                  This audio is AI-generated and personalized from your audit data and JahKnowsPR's report structure.
                </p>
                {data.estimatedMinutes ? (
                  <p className="mt-2">Estimated length: {data.estimatedMinutes} minutes.</p>
                ) : null}
              </div>
            </div>
          )}
        </div>
      </section>
    </main>
  );
}
