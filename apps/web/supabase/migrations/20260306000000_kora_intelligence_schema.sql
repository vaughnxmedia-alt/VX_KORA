-- KORA Intelligence System Schema
-- Core Intelligence: Data ingestion, RAG agents, and deliverables

-- Industry RAG Agents
-- Each industry gets its own knowledge base that strengthens with more data
CREATE TABLE public.kora_industry_rag_agents (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    industry TEXT NOT NULL UNIQUE,
    display_name TEXT NOT NULL,
    description TEXT,
    status TEXT NOT NULL DEFAULT 'building' CHECK (status IN ('active', 'building', 'inactive')),
    sources_count INTEGER DEFAULT 0,
    documents_count INTEGER DEFAULT 0,
    embeddings_count INTEGER DEFAULT 0,
    sync_frequency TEXT NOT NULL DEFAULT 'weekly' CHECK (sync_frequency IN ('daily', 'weekly', 'bi-weekly')),
    last_sync_at TIMESTAMPTZ,
    next_sync_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Ingest Sources (RSS feeds, APIs, scrapers)
CREATE TABLE public.kora_ingest_sources (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name TEXT NOT NULL,
    url TEXT NOT NULL,
    source_type TEXT NOT NULL DEFAULT 'rss' CHECK (source_type IN ('rss', 'api', 'scraper')),
    industry TEXT NOT NULL REFERENCES public.kora_industry_rag_agents(industry) ON DELETE CASCADE,
    is_active BOOLEAN DEFAULT true,
    last_fetch_at TIMESTAMPTZ,
    next_fetch_at TIMESTAMPTZ,
    items_count INTEGER DEFAULT 0,
    error_rate DECIMAL(5,4) DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Client Ingest Schedules (daily for JahKnowsPR, weekly for clients)
CREATE TABLE public.kora_ingest_schedules (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    customer_id UUID REFERENCES public.customers(id) ON DELETE CASCADE,
    frequency TEXT NOT NULL DEFAULT 'weekly' CHECK (frequency IN ('daily', 'weekly')),
    is_internal BOOLEAN DEFAULT false,
    last_run_at TIMESTAMPTZ,
    next_run_at TIMESTAMPTZ,
    status TEXT DEFAULT 'scheduled' CHECK (status IN ('scheduled', 'running', 'completed', 'failed')),
    items_ingested INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Ingested Items (parsed content from sources)
CREATE TABLE public.kora_ingested_items (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    source_id UUID REFERENCES public.kora_ingest_sources(id) ON DELETE SET NULL,
    title TEXT NOT NULL,
    url TEXT,
    content TEXT,
    snippet TEXT,
    author TEXT,
    published_at TIMESTAMPTZ,
    categories TEXT[],
    industry TEXT REFERENCES public.kora_industry_rag_agents(industry),
    is_embedded BOOLEAN DEFAULT false,
    embedding_id TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- KORA Agent Deliverables
-- Stores outputs from each KORA agent for each client
CREATE TABLE public.kora_deliverables (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    customer_id UUID REFERENCES public.customers(id) ON DELETE CASCADE,
    agent_id TEXT NOT NULL,
    agent_name TEXT NOT NULL,
    deliverable_type TEXT NOT NULL,
    title TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'in_progress', 'complete', 'failed')),
    content JSONB,
    file_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    completed_at TIMESTAMPTZ,
    sent_via_telegram BOOLEAN DEFAULT false,
    telegram_sent_at TIMESTAMPTZ
);

-- Content Strategies (generated by Content Strategy Agent)
CREATE TABLE public.kora_content_strategies (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    customer_id UUID REFERENCES public.customers(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    status TEXT DEFAULT 'draft' CHECK (status IN ('draft', 'active', 'archived')),
    content_pillars JSONB,
    weekly_themes JSONB,
    post_cadence JSONB,
    hashtag_strategy JSONB,
    target_personas TEXT[],
    recommended_channels TEXT[],
    key_messages TEXT[],
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Campaign Outputs (generated by Campaign Builder Agent)
CREATE TABLE public.kora_campaigns (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    customer_id UUID REFERENCES public.customers(id) ON DELETE CASCADE,
    strategy_id UUID REFERENCES public.kora_content_strategies(id) ON DELETE SET NULL,
    title TEXT NOT NULL,
    objective TEXT,
    status TEXT DEFAULT 'draft' CHECK (status IN ('draft', 'active', 'completed', 'archived')),
    campaign_posts JSONB,
    start_date DATE,
    end_date DATE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Audience Profiles (generated by Audience Intelligence Agent)
CREATE TABLE public.kora_audience_profiles (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    customer_id UUID REFERENCES public.customers(id) ON DELETE CASCADE,
    persona_name TEXT NOT NULL,
    demographics JSONB,
    behaviors JSONB,
    interests TEXT[],
    pain_points TEXT[],
    goals TEXT[],
    preferred_channels TEXT[],
    content_preferences JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Brand Identity (generated by Brand Identity Agent)
CREATE TABLE public.kora_brand_identities (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    customer_id UUID REFERENCES public.customers(id) ON DELETE CASCADE,
    tone_of_voice TEXT,
    brand_personality TEXT[],
    positioning_statement TEXT,
    key_messages TEXT[],
    do_say TEXT[],
    dont_say TEXT[],
    visual_direction JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Research Reports (generated by Research Agent)
CREATE TABLE public.kora_research_reports (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    customer_id UUID REFERENCES public.customers(id) ON DELETE CASCADE,
    report_type TEXT NOT NULL,
    title TEXT NOT NULL,
    industry_insights JSONB,
    competitor_analysis JSONB,
    market_trends JSONB,
    source_citations JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Telegram Integration Settings
CREATE TABLE public.kora_telegram_settings (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    chat_id TEXT NOT NULL,
    is_active BOOLEAN DEFAULT true,
    notify_on_deliverable BOOLEAN DEFAULT true,
    notify_on_ingest BOOLEAN DEFAULT false,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

