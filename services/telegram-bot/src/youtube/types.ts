/**
 * YouTube Pipeline Types
 */

export interface YouTubeClientConfig {
  apiKey?: string
  enableCaching?: boolean
  cacheTimeMs?: number
}

export interface TranscriptSegment {
  startMs: number
  endMs: number
  text: string
}

export type TranscriptionProvider = 
  | "youtube_captions" 
  | "auto_captions" 
  | "whisper" 
  | "assembly_ai" 
  | "manual"

export interface TranscriptExtractionResult {
  success: boolean
  videoId: string
  
  // Transcript content
  rawTranscript?: string
  normalizedTranscript?: string
  segments?: TranscriptSegment[]
  
  // Metadata
  language?: string
  source?: TranscriptionProvider
  confidence?: number
  wordCount?: number
  durationCoveredSeconds?: number
  
  // Errors
  error?: string
  errorCode?: string
}

export interface VideoMetadata {
  videoId: string
  title: string
  description: string
  channelId: string
  channelTitle: string
  publishedAt: string
  thumbnails: {
    default?: { url: string; width: number; height: number }
    medium?: { url: string; width: number; height: number }
    high?: { url: string; width: number; height: number }
    maxres?: { url: string; width: number; height: number }
  }
  duration: string
  tags?: string[]
  categoryId: string
}

export interface VideoStats {
  viewCount: number
  likeCount: number
  commentCount: number
}

export interface CaptionTrack {
  id: string
  language: string
  languageName: string
  isAutoGenerated: boolean
  isTranslatable: boolean
}

export interface YouTubePipelineResult {
  success: boolean
  videoId: string
  
  // Metadata
  metadata?: VideoMetadata
  stats?: VideoStats
  
  // Transcript
  transcript?: TranscriptExtractionResult
  
  // Processing
  processed: boolean
  processingTimeMs: number
  
  // Errors
  errors: string[]
}

export interface TranscriptionJobStatus {
  jobId: string
  videoId: string
  provider: TranscriptionProvider
  status: "queued" | "processing" | "completed" | "failed"
  progress?: number
  result?: TranscriptExtractionResult
  error?: string
  startedAt: Date
  completedAt?: Date
}
